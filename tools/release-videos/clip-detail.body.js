await p.goto(BASE + '/library');
await p.getByText('New Hire Onboarding', { exact: true }).first().waitFor({ timeout: 30000 });
await p.waitForTimeout(2500);
const marks = { start: t() };
await p.mouse.move(700, 300, { steps: 10 });
await p.waitForTimeout(600);
await glide(p, p.getByText('New Hire Onboarding', { exact: true }).first());
await p.getByText('Assignments').first().waitFor({ timeout: 30000 });
await p.waitForTimeout(3500);
