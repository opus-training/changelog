await smoothScroll(p, 520, 1600);
await p.waitForTimeout(2500);
await smoothScroll(p, -520, 1200);
await p.waitForTimeout(1200);
await glide(p, p.getByText('Reporting', { exact: true }).first());
await p.waitForTimeout(4500);
